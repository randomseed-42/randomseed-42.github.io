/** Derived edges: nodes from the same chapter first mentioned in the same conversation. */
function coMentioned(nodes: GraphNode[], existing: GraphEdge[]): GraphEdge[] {
  const has = new Set(existing.flatMap((e) => [`${e.source}|${e.target}`, `${e.target}|${e.source}`]))
  const out: GraphEdge[] = []
  const groups = new Map<string, GraphNode[]>()
  for (const n of nodes) {
    if (!n.chapter) continue
    const k = `${n.chapter}|${n.first_seen_week}`
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k)!.push(n)
  }
  for (const g of groups.values())
    for (let i = 1; i < g.length; i++) {
      const [a, b] = [g[i - 1].name, g[i].name]
      if (has.has(`${a}|${b}`)) continue
      has.add(`${a}|${b}`)
      out.push({ source: a, target: b, predicate: 'co_mentioned' })
    }
  return out
}

const EXPLICIT: GraphEdge[] = EDGE_ROWS.map(([s, t, predicate, fact]) => ({ source: key(s), target: key(t), predicate, ...(fact ? { fact } : {}) }))

export const EDGES: GraphEdge[] = [...EXPLICIT, ...coMentioned(NODES, EXPLICIT)]
